// Real Chromium proof for textarea admin save/reload, rendering, and classic HTTP.
import { createRequire } from 'node:module';
import fs from 'node:fs';
const require = createRequire(process.cwd() + '/index.js');
const { chromium } = require('playwright');
const base = process.env.OPF_BASE_URL || 'http://127.0.0.1:8126';
if (!/^http:\/\/127\.0\.0\.1:\d+$/.test(base)) throw new Error('Use disposable loopback site only.');
const dir = process.env.OPF_TEXTAREA_ARTIFACT_DIR || '/tmp/opf-textarea-artifacts';
fs.mkdirSync(dir, { recursive: true });
const state = JSON.parse(fs.readFileSync('/tmp/opf-textarea-state.json', 'utf8'));
const checks = [];
const check = (label, pass) => { checks.push({ label, pass: !!pass }); console.log(`${pass ? 'ok' : 'FAIL'} ${label}`); if (!pass) throw new Error(label); };
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 960 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(base + '/?opf_textarea_login=1', { waitUntil: 'domcontentloaded' });
  const first = page.locator('.opf-b-field').first();
  await first.waitFor();
  check('admin editor shows textarea field type', await first.locator('select').inputValue() === 'textarea');
  await first.locator('.opf-b-label').fill('Delivery note edited');
  await first.locator('input[title="Required"]').check();
  const savePromise = page.waitForResponse(r => r.url().includes('/opf/v1/groups') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  const saved = await savePromise;
  check('actual admin REST save succeeds', saved.ok());
  check('REST response retains textarea type and label', (await saved.json()).data.fields[0].type === 'textarea' && (await saved.json()).data.fields[0].label === 'Delivery note edited');
  await page.getByText('Saved.', { exact: true }).waitFor();
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.locator('.opf-b-field').first().waitFor();
  check('actual admin reload retains textarea type and edited label', await page.locator('.opf-b-field').first().locator('select').inputValue() === 'textarea' && await page.locator('.opf-b-field').first().locator('.opf-b-label').inputValue() === 'Delivery note edited');
  await page.screenshot({ path: dir + '/admin-reload.png', fullPage: true });
  await page.goto(base + '/product/opf-textarea-lifecycle/', { waitUntil: 'domcontentloaded' });
  const note = page.locator('[data-opf-field="note"] textarea');
  await note.waitFor();
  check('storefront renders textarea with accessible required semantics', await note.getAttribute('required') !== null && await note.getAttribute('name') !== null);
  check('storefront renders optional textarea', await page.locator('[data-opf-field="optional"] textarea').count() === 1 && await page.locator('[data-opf-field="optional"] textarea').getAttribute('required') === null);
  await page.screenshot({ path: dir + '/storefront-textarea.png', fullPage: true });
  let productPosts = 0;
  page.on('request', request => { if (request.method() === 'POST' && request.url().includes('/product/opf-textarea-lifecycle/')) productPosts++; });
  await page.locator('button.single_add_to_cart_button').click();
  check('browser blocks empty required textarea', await note.evaluate(node => !node.validity.valid) && productPosts === 0);
  const productId = await page.locator('button.single_add_to_cart_button').getAttribute('value');
  const name = await note.getAttribute('name');
  const forged = await page.request.post(base + '/product/opf-textarea-lifecycle/', { form: { 'add-to-cart': productId, quantity: '1', [name]: '' } });
  check('forged empty classic submission is rejected server-side', (await forged.text()).includes('is a required field'));
  const cart = await page.request.get(base + '/wp-json/wc/store/v1/cart');
  check('rejected classic request leaves cart empty', (await cart.json()).items.length === 0);
  await note.fill('First line\nSecond line & safe');
  await page.screenshot({ path: dir + '/storefront-multiline.png', fullPage: true });
  const nav = page.waitForNavigation({ waitUntil: 'domcontentloaded' });
  await page.locator('button.single_add_to_cart_button').click();
  await nav;
  check('browser classic product form submits multiline value', (await page.textContent('body')).includes('First line') && (await page.textContent('body')).includes('Second line'));
  const cartData = await (await page.request.get(base + '/wp-json/wc/store/v1/cart')).json();
  const cartValue = cartData.items[0]?.item_data.find(row => row.name === 'Delivery note edited')?.value || '';
  check('real cart API preserves CRLF value and escapes submitted markup', cartValue.includes('First line\r\nSecond line') && cartValue.includes('&amp; safe') && !cartValue.includes('<b>'));
  check('browser has no uncaught page errors', errors.length === 0);
} finally {
  fs.writeFileSync(dir + '/browser-results.json', JSON.stringify({ base, checks, errors }, null, 2));
  await browser.close();
}
